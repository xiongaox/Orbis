/**
 * 获取天干或地支的五行
 * @param char 天干或地支字符
 * @returns 'wood' | 'fire' | 'earth' | 'metal' | 'water' | ''
 */
export function getElement(char: string): string {
    return GAN_ELEMENT_MAP[char] || ZHI_ELEMENT_MAP[char] || '';
}

/**
 * 获取五行对应的颜色
 * @param char 天干或地支字符
 * @returns Hex Color String
 */
export function getElementColor(char: string): string {
    const element = getElement(char);
    return ELEMENT_COLORS[element] || 'currentColor';
}

/**
 * 计算旬空 (Xun Kong / Void)
 * @param ganZhi 干支字符串 (如 "甲子")
 * @returns 旬空字符串 (如 "戌亥")
 */
export function getXunKong(ganZhi: string): string {
    if (!ganZhi || ganZhi.length < 2) return '';
    const gan = ganZhi[0];
    const zhi = ganZhi[1];

    const ganList = TIAN_GAN;
    const zhiList = DI_ZHI;

    const ganIdx = ganList.indexOf(gan) + 1;
    const zhiIdx = zhiList.indexOf(zhi) + 1;

    let diff = ganIdx - zhiIdx;
    if (diff <= 0) diff += 12;

    const lookup: Record<number, string> = {
        12: '戌亥', 10: '子丑', 8: '寅卯', 6: '辰巳', 4: '午未', 2: '申酉'
    };
    return lookup[diff] || '';
}

