/**
 * 根据日主和目标干支计算十神
 * 对于地支，使用其本气天干来计算
 * @param dayMaster 日主天干
 * @param target 目标天干或地支
 * @returns 十神全称
 */
export function getShiShen(dayMaster: string, target: string): string {
    // 如果是地支，先转换为本气天干
    const actualTarget = ZHI_BEN_QI[target] || target;

    const day = ELEMENT_META[dayMaster];
    const meta = ELEMENT_META[actualTarget];
    if (!day || !meta) return '';

    const samePolarity = day.polarity === meta.polarity;
    if (meta.element === day.element) {
        return samePolarity ? '比肩' : '劫财';
    }
    if (meta.element === ELEMENT_GENERATES[day.element]) {
        return samePolarity ? '食神' : '伤官';
    }
    if (meta.element === ELEMENT_CONTROLS[day.element]) {
        return samePolarity ? '偏财' : '正财';
    }
    if (meta.element === ELEMENT_GENERATED_BY[day.element]) {
        return samePolarity ? '偏印' : '正印';
    }
    if (meta.element === ELEMENT_CONTROLLED_BY[day.element]) {
        return samePolarity ? '七杀' : '正官';
    }
    return '';
}

/**
 * 获取十神缩写
 * @param dayMaster 日主天干
 * @param target 目标天干或地支
 * @returns 十神缩写（单字）
 */
export function getShiShenAbbr(dayMaster: string, target: string): string {
    return SHI_SHEN_ABBR[getShiShen(dayMaster, target)] ?? '';
}

